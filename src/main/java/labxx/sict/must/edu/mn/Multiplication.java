package labxx.sict.must.edu.mn;

/**
 * Үржүүлэх үйлдлийг гүйцэтгэх класс.
 */
public class Multiplication {
    /**
     * Хоёр тоог үржүүлнэ.
     *
     * @param a Эхний тоо
     * @param b Хоёр дахь тоо
     * @return Үржүүлгийн үр дүн
     */
    public double multiply(final double a, final double b) {
        return a * b;
    }
}
