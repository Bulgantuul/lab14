package labxx.sict.must.edu.mn;

/**
 * Хасах үйлдлийг гүйцэтгэх класс.
 */
public class Subtraction {
    /**
     * Эхний тооноос хоёр дахь тоог хасна.
     *
     * @param a Хасагдагч (Minuend)
     * @param b Хасагч (Subtrahend)
     * @return Хасах үйлдлийн үр дүн
     */
    public double subtract(final double a, final double b) {
        return a - b;
    }
}
